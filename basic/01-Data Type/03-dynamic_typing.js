// dynamic typing by assigning a different data type to the same variable one after another

let value = 10;
console.log(value, typeof value);

value = "Hello";
console.log(value, typeof value);

value = true;
console.log(value, typeof value);

value = null;
console.log(value, typeof value);

value = [1, 2, 3];
console.log(value, typeof value);

value = {
    name: "Rahul",
    age: 20
};
console.log(value, typeof value);
