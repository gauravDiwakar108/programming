// demonstrates the difference between == and ===

console.log(5 == "5");
console.log(5 === "5");

console.log(true == 1);
console.log(true === 1);

console.log(false == 0);
console.log(false === 0);

console.log(null == undefined);
console.log(null === undefined);

console.log("10" == 10);
console.log("10" === 10);
